#!/usr/bin/env node
// Generate docs/api.md from the types the package actually ships.
//
// Written rather than hand-maintained for one reason: a reference that is typed out
// by hand is wrong the first time somebody renames a prop and does not think to open
// the docs. This reads the emitted `.d.ts` files, which are generated from the JSDoc
// on the components, which is the same text an editor shows on hover. One source,
// three places it turns up, no way for them to disagree.
//
// Run `pnpm build` first -- this reads `dist/types`, not `src`.
//
//   node scripts/api-reference.mjs [--check]
//
// `--check` fails instead of writing, for CI: it means the reference has drifted from
// the code and needs regenerating.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const types = join(root, 'packages/core/dist/types/components')
const out = join(root, 'docs/api.md')
const check = process.argv.includes('--check')

if (!existsSync(types)) {
  console.error('No dist/types. Run `pnpm build` first.')
  process.exit(1)
}

/**
 * What a studio author writes, and what the framework renders for them.
 *
 * Deliberately a list rather than "everything exported". `Menu`, `SyncStatus`,
 * `RelayAdmin` and the dialogs are real components with real props, and none of them
 * is something a studio author places -- `ControlPage` renders them. Documenting
 * them here would triple the page and bury the twenty that matter.
 */
const AUTHORED = {
  control: [
    'Field',
    'Stepper',
    'Select',
    'Cycle',
    'ColorPicker',
    'ImagePicker',
    'ImageSelect',
    'ImageToggle',
    'ToggleButton',
    'SwapButton',
    'ResetButton',
    'Countdown',
    'CountdownTo',
    'Stopwatch',
    'Leaderboard',
    'Panel',
    'Break',
    'SaveButton',
    'Confirm',
  ],
  source: ['Scene', 'Variable', 'Image', 'ImageList', 'Toggle', 'Timer', 'Ticker', 'Clock'],
}

/** First sentence of a doc comment: what the thing is, before why it is that way. */
function summarise(text) {
  const body = text
    .split('\n')
    .map((line) => line.replace(/^\s*\/?\*+\/?\s?/, '').trim())
    .filter(Boolean)

  const first = body.findIndex((line) => line && !line.startsWith('@'))

  if (first === -1) return ''

  const sentence = []

  for (const line of body.slice(first)) {
    if (!line || line.startsWith('@')) break

    sentence.push(line)

    if (/[.!?]$/.test(line)) break
  }

  return sentence.join(' ')
}

/** Props out of an emitted `export type XProps = { … }` block. */
function propsOf(source, component) {
  const start = source.indexOf(`export type ${component}Props = {`)

  if (start === -1) return null

  const end = source.indexOf('\n};', start)
  const block = source.slice(start, end)
  const props = []

  // Entries alternate: a doc comment, then the member it belongs to.
  const pattern = /\/\*\*\s*\n((?:\s*\*.*\n)*?)\s*\*\/\s*\n\s*(\w+)(\??):\s*([^;]+);/g

  for (const [, comment, name, optional, kind] of block.matchAll(pattern)) {
    props.push({
      name,
      required: optional !== '?',
      type: kind
        .replace(/\s+/g, ' ')
        .replace(/import\("react"\)\./g, '')
        .trim(),
      description: comment
        .split('\n')
        .map((line) => line.replace(/^\s*\*\s?-?\s?/, '').trim())
        .filter(Boolean)
        .join(' '),
    })
  }

  return props
}

const files = new Map()

for (const kind of ['control', 'source']) {
  for (const file of readdirSync(join(types, kind))) {
    if (file.endsWith('.d.ts')) files.set(file.replace('.d.ts', ''), readFileSync(join(types, kind, file), 'utf8'))
  }
}

function render(component) {
  const source = files.get(component)

  if (!source) return `### \`${component}\`\n\n_Not found in dist/types — was it renamed?_\n`

  const declaration = source.indexOf(`export declare function ${component}(`)
  const before = source.lastIndexOf('/**', declaration)
  const summary = before === -1 ? '' : summarise(source.slice(before, declaration))
  const props = propsOf(source, component) ?? []

  const lines = [`### \`${component}\``, '', summary]

  if (props.length) {
    lines.push(
      '',
      '| Prop | Type | |',
      '| --- | --- | --- |',
      // A union type contains pipes, and a pipe inside a markdown table cell ends
      // the cell. Escaped rather than reformatted, so the type printed is the type.
      ...props.map((p) => `| \`${p.name}\`${p.required ? ' **·** required' : ''} | \`${p.type.replace(/\|/g, '\\|')}\` | ${p.description} |`),
    )
  }

  return `${lines.join('\n')}\n`
}

const page = `<!-- Generated by scripts/api-reference.mjs. Edit the JSDoc on the components instead. -->

# Component reference

Every piece of state has two components — one on the operator's board, one on air —
and they meet at a path. That pairing is the whole mental model:

| What it is       | On the board                  | On air         | Lives under |
| ---------------- | ----------------------------- | -------------- | ----------- |
| Text             | \`Field\`                       | \`Variable\`     | \`variables\` |
| Number           | \`Stepper\`                     | \`Variable\`     | \`variables\` |
| One of a list    | \`Select\`, \`Cycle\`             | \`Variable\`     | \`variables\` |
| Colour           | \`ColorPicker\`                 | \`Scene\` \`vars\` | \`variables\` |
| A picture        | \`ImagePicker\`, \`ImageSelect\`  | \`Image\`        | \`variables\` |
| Several pictures | \`ImageSelect\` \`multiple\`      | \`ImageList\`    | \`variables\` |
| On or off        | \`ToggleButton\`, \`ImageToggle\` | \`Toggle\`       | \`toggles\`   |
| Counting down    | \`Countdown\`, \`CountdownTo\`    | \`Timer\`        | \`timers\`    |
| Counting up      | \`Stopwatch\`                   | \`Timer\`        | \`timers\`    |
| Scrolling text   | \`Field\`                       | \`Ticker\`       | \`variables\` |
| Wall clock       | —                             | \`Clock\`        | —           |

Every component takes \`name\` plus a \`namespace\` that defaults to the right one, so a
studio author writes \`name="home.score"\` and rarely thinks about namespaces at all.
Every component also passes anything it does not recognise through to the DOM, so
\`style\`, \`data-*\` and the rest stay available.

## On the board

${AUTHORED.control.map(render).join('\n')}
## On air

${AUTHORED.source.map(render).join('\n')}`

if (check) {
  const existing = existsSync(out) ? readFileSync(out, 'utf8') : ''

  if (existing !== page) {
    console.error('docs/api.md is out of date. Run `pnpm api:reference`.')
    process.exit(1)
  }

  console.log('docs/api.md matches the shipped types')
} else {
  writeFileSync(out, page)
  console.log(`wrote ${out}`)
}
